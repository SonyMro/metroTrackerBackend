CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS genero (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS usuario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(100) NOT NULL,

    apepat VARCHAR(100) NOT NULL,

    apemat VARCHAR(100),

    foto BYTEA,

    correo VARCHAR(254) NOT NULL,

    password VARCHAR(255) NOT NULL,

    fecharegistro TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    fehcaact TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    idrol INTEGER NOT NULL,

    idgenero INTEGER NOT NULL,

    esactivo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_usuario_correo
        UNIQUE (correo),

    CONSTRAINT fk_usuario_rol
        FOREIGN KEY (idrol)
        REFERENCES roles(id),

    CONSTRAINT fk_usuario_genero
        FOREIGN KEY (idgenero)
        REFERENCES genero(id)
);

CREATE INDEX IF NOT EXISTS idx_usuario_idrol
    ON usuario(idrol);

CREATE INDEX IF NOT EXISTS idx_usuario_idgenero
    ON usuario(idgenero);

CREATE INDEX IF NOT EXISTS idx_usuario_esactivo
    ON usuario(esactivo);

